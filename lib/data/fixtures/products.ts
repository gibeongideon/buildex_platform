export function seedProducts(): Product[] {
  return ROWS.map((r, i) => ({
    id: r.id,
    manufacturerId: r.m,
    name: r.name,
    category: r.category,
    sku: r.sku,
    description: r.description,
    unit: r.unit,
    packSize: r.packSize,
    priceBands: r.bands.map(([minQty, maxQty, unitPrice]) => ({ minQty, maxQty, unitPrice })),
    moq: r.moq,
    leadTimeDays: r.lead,
    availableRegions: r.regions,
    imageUrls: [],
    status: r.status ?? "active",
    createdAt: daysAgo(90 - i),
    updatedAt: daysAgo(Math.max(30 - i, 1)),
  }));
}
